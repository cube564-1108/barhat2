def get_category_names():
    """Список названий категорий для UI."""
    return [cat["name"] for cat in EXPENSE_CATEGORIES]

def find_category_id_by_name(cursor, category_name):
    """Найти ID категории по названию."""
    result = cursor.execute(
        "SELECT id FROM expense_categories WHERE name = ? AND is_active = 1",
        (category_name,)
    ).fetchone()
    return result[0] if result else None

def find_store_id_by_name(cursor, store_name):
    """Найти ID точки по названию."""
    result = cursor.execute(
        "SELECT id FROM stores WHERE name = ? AND is_active = 1",
        (store_name,)
    ).fetchone()
    return result[0] if result else None


