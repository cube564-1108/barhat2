# =============================================================================

def get_insert_stores_sql():
    """Генерирует SQL для вставки точек продаж."""
    values = ", ".join([f"('{store['name']}')" for store in STORES])
    return f"""
    INSERT INTO stores (name, is_active) VALUES
    {values};
    """

def get_insert_categories_sql():
    """Генерирует SQL для вставки категорий расходов."""
    values = ", ".join([f"('{cat['name']}')" for cat in EXPENSE_CATEGORIES])
    return f"""
    INSERT INTO expense_categories (name, is_active) VALUES
    {values};
    """


