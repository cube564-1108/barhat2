# Отпечаток выкаченного кода. Один и тот же файл во всех сервисах БАРХАТ.
#
# Зачем: в Пульсе, раздел «Система» → «Обновления», лента показывает, что и когда
# выкатили. До сих пор туда попадал только сам Пульс - остальные сервисы никак не
# сообщали, что поднялись с новым кодом. Теперь заготовщик workers раз в 5 минут
# смотрит /health каждого сервиса: сменился отпечаток - значит был деплой, и в ленте
# появляется новая версия с описаниями из коммитов.
#
# Ничего не отправляет и никуда не пишет: только читает свои же .py и считает sha1.
# Отпечаток, а не хэш коммита, - намеренно: не зависит от того, кладёт ли Amvera
# папку .git в контейнер, и одинаково работает во всех сервисах.
#
# План: plans/обновления-всех-сервисов/план.md (репозиторий barkhat).

import hashlib
import os

_CACHE: str | None = None

# Каталоги, которые к выкаченному коду отношения не имеют: кэш интерпретатора,
# окружения, тома с данными. Иначе отпечаток менялся бы сам по себе на ходу.
_SKIP_DIRS = {".git", "__pycache__", ".venv", "venv", "node_modules", "log", "logs", "data", "tests"}


def build_fingerprint() -> str:
    """sha1 по содержимому всех .py сервиса.

    Считается один раз за жизнь процесса, дальше отдаётся из памяти: в контейнере
    файлы меняются только деплоем, пересчитывать на каждый запрос /health незачем.
    """
    global _CACHE
    if _CACHE is not None:
        return _CACHE
    root = os.path.dirname(os.path.abspath(__file__))
    h = hashlib.sha1()
    for dirpath, dirnames, filenames in os.walk(root):
        # Порядок обхода обязан быть одинаковым от запуска к запуску, иначе один и тот же
        # код давал бы разные отпечатки: сортируем и каталоги, и файлы.
        dirnames[:] = sorted(d for d in dirnames if d not in _SKIP_DIRS)
        for name in sorted(filenames):
            if not name.endswith(".py"):
                continue
            path = os.path.join(dirpath, name)
            # Путь в отпечаток тоже идёт: переименование файла - это тоже новый код.
            h.update(os.path.relpath(path, root).replace("\\", "/").encode("utf-8"))
            try:
                with open(path, "rb") as f:
                    h.update(f.read())
            except OSError:
                # Файл исчез между обходом и чтением - пропускаем: отпечаток нужен
                # приблизительно стабильным, а не идеальным, и /health падать не должен.
                continue
    _CACHE = h.hexdigest()
    return _CACHE
